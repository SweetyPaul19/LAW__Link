document.addEventListener("DOMContentLoaded", () => {
  const categoryButtons = document.querySelectorAll(".category-btn");
  const categoryInfo = document.getElementById("categoryInfo");
  let selectedCategory = "street";

  const CATEGORY_META = {
    street: {
      label: "Street / Public Harassment",
      recipient: "The Station House Officer",
      recipientNote: "Nearest Police Station",
      info: "Covered under provisions for outraging modesty and stalking (IPC 354/354A/354D, now Sections 74/75/78 of the Bharatiya Nyaya Sanhita). File this at your nearest police station or via the 112 app.",
      legalRef: "This complaint is made with reference to provisions protecting against outraging the modesty of a woman and criminal intimidation in a public place.",
    },
    workplace: {
      label: "Workplace Harassment",
      recipient: "The Presiding Officer, Internal Committee (IC)",
      recipientNote: "Your Organization's Internal Committee (as per the POSH Act)",
      info: "Covered under the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013 (POSH Act). Every employer with 10+ employees must have an Internal Committee to receive this complaint.",
      legalRef: "This complaint is made under the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013, and should be addressed to the Internal Committee constituted under Section 4 of the Act.",
    },
    stalking: {
      label: "Stalking",
      recipient: "The Station House Officer",
      recipientNote: "Nearest Police Station",
      info: "Stalking (including repeated unwanted contact, following, or monitoring) is a specific criminal offence under IPC 354D (now BNS provisions). Save any messages, call logs, or photos as evidence.",
      legalRef: "This complaint concerns an offence of stalking as defined under the applicable penal provisions, including repeated attempts to contact or monitor the complainant despite clear disinterest.",
    },
    cyber: {
      label: "Online / Cyber Harassment",
      recipient: "The Cyber Crime Cell",
      recipientNote: "Local Cyber Crime Cell / cybercrime.gov.in",
      info: "Covered under the Information Technology Act, 2000 (Sections 66E, 67, 67A) and relevant penal provisions for online abuse, morphed images, or threats. You can also file directly at cybercrime.gov.in.",
      legalRef: "This complaint is made with reference to the Information Technology Act, 2000 and applicable penal provisions concerning online harassment, threats, or non-consensual sharing of images/content.",
    },
  };

  function updateCategoryInfo() {
    categoryInfo.textContent = CATEGORY_META[selectedCategory].info;
  }

  categoryButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      categoryButtons.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      selectedCategory = btn.dataset.category;
      updateCategoryInfo();
    });
  });
  updateCategoryInfo();

  const qhcForm = document.getElementById("qhcForm");
  const qhcOutputWrap = document.getElementById("qhcOutputWrap");
  const qhcOutput = document.getElementById("qhcOutput");
  let lastDraft = "";

  function formatDate(dateStr) {
    if (!dateStr) return "";
    const d = new Date(dateStr + "T00:00:00");
    return d.toLocaleDateString("en-IN", { day: "2-digit", month: "long", year: "numeric" });
  }

  function buildDraft(data) {
    const meta = CATEGORY_META[data.category];
    return `COMPLAINT REGARDING ${meta.label.toUpperCase()}

Date: ${formatDate(data.date)}

To,
${meta.recipient}
${meta.recipientNote}

From,
${data.name}

Subject: Complaint regarding ${meta.label.toLowerCase()} on ${formatDate(data.date)} at ${data.location}

Respected Sir/Madam,

I, ${data.name}, wish to file a formal complaint regarding an incident of ${meta.label.toLowerCase()} that occurred on ${formatDate(data.date)} at ${data.location}.

DETAILS OF INCIDENT:
${data.description}

${data.accused ? `PERSON(S) INVOLVED:\n${data.accused}\n` : ""}${data.witness ? `WITNESS(ES):\n${data.witness}\n` : ""}
${meta.legalRef}

I request that this complaint be registered and appropriate action be taken at the earliest. I am available to provide any further information or evidence required.

Yours faithfully,
${data.name}

---
This is an AI-assisted draft generated by LawLink's Quick Harassment Complaint tool. It is intended as a
starting point only. Please review with a lawyer, your Internal Committee, or the relevant authority before submission.`;
  }

  qhcForm.addEventListener("submit", (e) => {
    e.preventDefault();
    const data = {
      name: document.getElementById("qhcName").value.trim(),
      date: document.getElementById("qhcDate").value,
      location: document.getElementById("qhcLocation").value.trim(),
      accused: document.getElementById("qhcAccused").value.trim(),
      description: document.getElementById("qhcDescription").value.trim(),
      witness: document.getElementById("qhcWitness").value.trim(),
      category: selectedCategory,
    };

    lastDraft = buildDraft(data);
    qhcOutput.textContent = lastDraft;
    qhcOutputWrap.classList.remove("hidden");
    qhcOutputWrap.scrollIntoView({ behavior: "smooth", block: "start" });
  });

  document.getElementById("qhcCopy").addEventListener("click", async () => {
    if (!lastDraft) return;
    try {
      await navigator.clipboard.writeText(lastDraft);
      alert("Draft copied to clipboard.");
    } catch {
      alert("Could not copy automatically — please select and copy the text manually.");
    }
  });

  document.getElementById("qhcDownloadPdf").addEventListener("click", () => {
    if (!lastDraft) return;
    if (!window.jspdf) {
      alert("PDF library failed to load. Please copy the text instead.");
      return;
    }
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const margin = 48;
    const maxWidth = 595 - margin * 2;
    const lines = doc.splitTextToSize(lastDraft, maxWidth);
    doc.setFont("Times", "Normal");
    doc.setFontSize(11);

    let y = margin;
    const lineHeight = 16;
    const pageHeight = 842;

    lines.forEach(line => {
      if (y > pageHeight - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += lineHeight;
    });

    doc.save("quick-harassment-complaint.pdf");
  });

  document.getElementById("qhcDate").valueAsDate = new Date();
});