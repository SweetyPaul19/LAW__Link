document.addEventListener("DOMContentLoaded", () => {
  const tabs = document.querySelectorAll(".jm-tab");
  const panels = {
    dowry: document.getElementById("panel-dowry"),
    dv: document.getElementById("panel-dv"),
    divorce: document.getElementById("panel-divorce"),
  };
  const jmType = document.getElementById("jmType");

  tabs.forEach(tab => {
    tab.addEventListener("click", () => {
      tabs.forEach(t => t.classList.remove("active"));
      tab.classList.add("active");
      const key = tab.dataset.tab;
      Object.entries(panels).forEach(([k, el]) => {
        el.classList.toggle("hidden", k !== key);
      });
      if (jmType && [...jmType.options].some(o => o.value === key)) {
        jmType.value = key;
      }
    });
  });

  const jmForm = document.getElementById("jmForm");
  const jmOutputWrap = document.getElementById("jmOutputWrap");
  const jmOutput = document.getElementById("jmOutput");

  const TITLES = {
    dowry: "COMPLAINT REGARDING DOWRY HARASSMENT",
    dv: "COMPLAINT UNDER THE PROTECTION OF WOMEN FROM DOMESTIC VIOLENCE ACT, 2005",
    divorce: "LEGAL NOTICE REGARDING MATRIMONIAL DISPUTE / DIVORCE",
  };

  const LEGAL_REFS = {
    dowry: "This complaint is made with reference to the Dowry Prohibition Act, 1961 and applicable provisions relating to cruelty for dowry demands.",
    dv: "This complaint is made under the Protection of Women from Domestic Violence Act, 2005, seeking protection, residence, and/or monetary relief as applicable.",
    divorce: "This notice concerns matrimonial relief including separation, maintenance, and/or custody arrangements as applicable under the relevant personal law.",
  };

  function formatDate(dateStr) {
    if (!dateStr) return "";
    const d = new Date(dateStr + "T00:00:00");
    return d.toLocaleDateString("en-IN", { day: "2-digit", month: "long", year: "numeric" });
  }

  function buildDraft(data) {
    return `${TITLES[data.type]}

Date: ${formatDate(data.date)}

From:
${data.name}
${data.address}

To:
${data.respondent}

Subject: ${TITLES[data.type]}

Respected Sir/Madam,

I, ${data.name}, residing at ${data.address}, wish to bring to your attention the following matter concerning ${data.respondent}.

DETAILS OF INCIDENT(S):
${data.details}

RELIEF / ACTION REQUESTED:
${data.relief}

${LEGAL_REFS[data.type]}

I request that appropriate action be taken at the earliest and that this matter be treated with the seriousness it deserves.

Yours faithfully,
${data.name}

---
This is an AI-assisted draft generated by LawLink's JusticeMate tool. It is intended as a starting point only.
Please have this reviewed by a qualified advocate before formal submission or service.`;
  }

  let lastDraft = "";

  jmForm.addEventListener("submit", (e) => {
    e.preventDefault();
    const data = {
      name: document.getElementById("jmName").value.trim(),
      date: document.getElementById("jmDate").value,
      address: document.getElementById("jmAddress").value.trim(),
      respondent: document.getElementById("jmRespondent").value.trim(),
      type: document.getElementById("jmType").value,
      details: document.getElementById("jmDetails").value.trim(),
      relief: document.getElementById("jmRelief").value.trim(),
    };

    lastDraft = buildDraft(data);
    jmOutput.textContent = lastDraft;
    jmOutputWrap.classList.remove("hidden");
    jmOutputWrap.scrollIntoView({ behavior: "smooth", block: "start" });
  });

  document.getElementById("jmCopy").addEventListener("click", async () => {
    if (!lastDraft) return;
    try {
      await navigator.clipboard.writeText(lastDraft);
      alert("Draft copied to clipboard.");
    } catch {
      alert("Could not copy automatically — please select and copy the text manually.");
    }
  });

  document.getElementById("jmDownloadPdf").addEventListener("click", () => {
    if (!lastDraft) return;
    if (!window.jspdf) {
      alert("PDF library failed to load. Please copy the text instead.");
      return;
    }
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const margin = 48;
    const maxWidth = 595 - margin * 2;
    const lines = doc.splitTextToSize(lastDraft, maxWidth);
    doc.setFont("Times", "Normal");
    doc.setFontSize(11);

    let y = margin;
    const lineHeight = 16;
    const pageHeight = 842;

    lines.forEach(line => {
      if (y > pageHeight - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += lineHeight;
    });

    doc.save("justicemate-draft.pdf");
  });

  document.getElementById("jmDate").valueAsDate = new Date();
});